const fs = require('fs');
const path = require('path');

/**
 * Generates multiple Mermaid-based data flow diagram pages
 * Split into digestible chunks with zoom/pan support
 */
function generateMermaidFlows(data, outputDir, getSharedStyles, getSidebar) {
  const flows = [
    { id: 'auth', name: 'Authentication Flow', icon: '🔐', generator: generateAuthFlow },
    { id: 'payment', name: 'Payment Flow', icon: '💳', generator: generatePaymentFlow },
    { id: 'data', name: 'Data Flow', icon: '📊', generator: generateDataFlow },
    { id: 'storage', name: 'Storage Flow', icon: '💾', generator: generateStorageFlow },
    { id: 'api', name: 'API Overview', icon: '🔌', generator: generateApiOverview },
    { id: 'deployment', name: 'Deployment Flow', icon: '🚀', generator: generateDeploymentFlow, multiDiagram: true },
    { id: 'architecture', name: 'Architecture Overview', icon: '🏗️', generator: generateArchitectureOverview, multiDiagram: true },
    { id: 'security', name: 'Security Audit', icon: '🔒', generator: generateSecurityAudit },
    { id: 'onboarding', name: 'Onboarding Flow', icon: '📚', generator: generateOnboardingFlow, multiDiagram: true },
  ];

  // Generate index page for all flows
  const indexHTML = generateFlowIndex(data, flows, getSharedStyles, getSidebar);
  fs.writeFileSync(path.join(outputDir, 'data-flow.html'), indexHTML);

  // Generate individual flow pages
  flows.forEach(flow => {
    const html = generateFlowPage(data, flow, flows, getSharedStyles, getSidebar);
    fs.writeFileSync(path.join(outputDir, `flow-${flow.id}.html`), html);
  });

  return flows;
}

